const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

function generateImageCache(root = path.resolve(__dirname, '..')) {
  const versions = {};
  const directory = path.join(root, 'imagens');
  for (const entry of fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isFile() || !/\.(svg|png|jpe?g|webp|gif|avif)$/i.test(entry.name)) continue;
    versions[entry.name] = crypto.createHash('sha256')
      .update(fs.readFileSync(path.join(directory, entry.name))).digest('hex').slice(0, 16);
  }

  const writeIfChanged = (file, content) => {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) fs.writeFileSync(file, content);
  };
  fs.mkdirSync(path.join(root, 'js'), { recursive: true });
  writeIfChanged(path.join(root, 'js/image-versions.js'),
    '// Generated by scripts/generate-image-cache.cjs. Do not edit manually.\n' +
    `window.MusicQuizImageVersions = ${JSON.stringify(versions, null, 2)};\n`);

  // Give initial HTML images the same URL as preloaded/dynamic images, avoiding
  // a second download of the 25 MB start screen under a different cache key.
  const indexFile = path.join(root, 'index.html');
  const html = fs.readFileSync(indexFile, 'utf8').replace(/\b(src|href)="imagens\/([^"?]+)(?:\?[^"\s]*)?"/g,
    (_, attribute, encodedName) => {
      const name = decodeURIComponent(encodedName);
      if (!versions[name]) throw new Error(`No se encontró la imagen: ${name}`);
      return `${attribute}="imagens/${encodeURIComponent(name)}?v=${versions[name]}"`;
    });
  writeIfChanged(indexFile, html);
  return versions;
}

module.exports = { generateImageCache };
if (require.main === module) {
  const versions = generateImageCache();
  console.log(`Listo: ${Object.keys(versions).length} imágenes versionadas para el caché. Los originales no se modificaron.`);
}
